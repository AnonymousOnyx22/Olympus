/** Compact text for the brief. Short on purpose: the agent should choose, not read an essay. */
export function describeBusinessModels(): string {
  return BUSINESS_MODELS.map((m, i) => `${i + 1}. ${m.name}: ${m.sells} Stack: ${m.stack} Owner sets up once: ${m.ownerSetup} First sale: ${m.timeToFirstSale} Risk: ${m.honestRisk}`).join(' ')
}

export function describeThemes(): string {
  return STORE_THEMES.map((t) => `${t.name} (${t.mood}; palette ${t.palette}; type: ${t.type}; layout: ${t.layout}; motion: ${t.motion}; suits ${t.bestFor})`).join(' | ')
}
