/**
 * What a Station agent can choose to build, and how it should look. Kept as data so the brief,
 * the plan, and the tests all read the same list instead of drifting apart.
 *
 * Every model here has to run with no work from the owner and no fixed cost. "Time to first sale"
 * is deliberately blunt: most of these take months, and the agent must say so instead of promising
 * income.
 */

